#!/usr/bin/env node
// Rehearses the demo against the real app and the real kernel. Needs `make run` going, and Google Chrome.
const { chromium } = require('../app/node_modules/playwright')
const URL = process.env.URL || 'http://localhost:4173'
const T = 180000
const settled = p => p.waitForFunction(() => { const v = document.querySelector('.verdict,.verify-card'); return v && !document.querySelector('.verdict.busy') }, null, { timeout: T })
const verdict = p => p.waitForFunction(() => document.querySelector('.verdict') && !document.querySelector('.verdict.busy'), null, { timeout: T })
let passed = 0
process.on('exit', () => {})
const ok = (cond, what) => { if (!cond) { console.error(`  ✕ ${what}`); process.exit(1) } console.log(`  ✓ ${what}`); passed++ }
const heading = s => console.log(s)
const paneOf = (p, name) => p.click(`.rail-tabs button:has-text("${name}")`)
;(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] })
  const c = await b.newContext({ viewport: { width: 1440, height: 900 } }); const p = await c.newPage()
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
  const fp = () => p.locator('.rail').getAttribute('data-fingerprint')
  const states = () => p.locator('.gauge .g-top em').allTextContents()

  heading('Act 1: it opens on the stage')
  await p.goto(URL); await p.waitForSelector('.director-home .director', { timeout: T })
  ok(await p.locator('.dr-msg').count() === 1, 'the Studio opens on the conversation, with no login')
  await p.goto(`${URL}/#/create/midnight-in-motion`); await p.waitForSelector('.plan', { timeout: T })
  
  ok((await p.textContent('.proj h2')).toLowerCase().includes('midnight'), 'Midnight in Motion opens from the Library')
  await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved.', 'Lean proves it')
  ok((await states()).every(s => s.startsWith('Proved')), 'Movement is verified, and it is the only claim')
  ok(await p.locator('.gauge').count() === 4, 'four proofs on a routine with no allowance')
  const originalFp = await fp()
  await p.click('.round'); await p.waitForTimeout(1500); await p.click('.round')
  ok(await p.textContent('.time') !== '0:00 / 0:15', 'it plays')

  heading('The Lean tab holds the detail')
  await p.click('.tab:has-text("Proofs")'); ok(/Say this/.test(await p.textContent('.lean-panel')) && /A video can't show safety/.test(await p.textContent('.lean-panel')), 'it explains the proofs in plain words')
  await p.click('.lp-tabs >> text=The four proofs'); await p.waitForFunction(() => /MovementProved/.test(document.querySelector('.lean-panel').textContent), null, { timeout: T })
  ok(true, 'it shows the real statement from the checked file')
  ok(await p.locator('.lp-rule').count() === 4 && /PhaseSpec.speedLimit/.test(await p.textContent('.lean-panel')) && /joinPath_sound/.test(await p.textContent('.lean-panel')), 'each rule names its theorem')
  await p.click('.lp-tabs >> text=How they fail'); ok(/refute_collision/.test(await p.textContent('.lean-panel')), 'it says how each rule fails')
  await p.click('.lp-tabs >> text=Source'); await p.waitForFunction(() => document.querySelector('.lean-panel .xsource')?.textContent.includes('routine_moves_safely'), null, { timeout: T }); ok(true, 'the source is there for anyone who wants it')
  await p.click('.lean-panel >> text=Generate Lean proof'); await p.waitForTimeout(300); await verdict(p); ok(await p.textContent('.verdict h2') === 'Proved.', 'a proof can be generated on demand')
  await p.click('.tab:has-text("Formations")')

  heading('Act 4: break it. Finn moves one row upstage')
  await p.click('[data-f="2"]'); await p.waitForTimeout(400)
  const svg = await p.locator('.plan > svg').boundingBox(), scale = Math.min(svg.width / 21600, svg.height / 9900)
  const ox = svg.x + svg.width / 2, oy = svg.y + (svg.height - 9900 * scale) / 2 + 1200 * scale, X = x => ox + x * scale, Y = y => oy + (8000 - y) * scale
  const drag = async (x0, y0, x1, y1) => { await p.mouse.move(X(x0), Y(y0)); await p.mouse.down(); await p.mouse.move((X(x0) + X(x1)) / 2, (Y(y0) + Y(y1)) / 2, { steps: 4 }); await p.mouse.move(X(x1), Y(y1), { steps: 4 }); await p.waitForTimeout(100); const t = await p.locator('.plan > svg').textContent(); await p.mouse.up(); return t }
  const preview = await drag(0, 5500, 0, 7000)
  ok(/Would clash with|Closest:/.test(preview), 'a preview appears while dragging')
  await p.waitForSelector('.verify-card', { timeout: 20000 }); await p.waitForTimeout(300)
  ok((await p.textContent('.verify-card')).includes('not checked'), 'the edit is not checked, and the old proof is not reused')
  ok(await p.locator('.verify-card:has-text("not a result from Lean")').count() === 1, 'the warning says it is a preview')
  ok((await states()).every(s => s.startsWith('Not checked')), 'no category claims anything')
  await p.click('.tab:has-text("Formations")'); await p.waitForTimeout(200)
  await p.click('text=Verify choreography'); await p.waitForTimeout(300); await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved unsafe.', 'the kernel refutes it')
  ok((await p.textContent('.time')).endsWith('0:15'), 'the edit keeps the routine\'s exact timing')
  const brokenFp = await fp(); ok(brokenFp !== originalFp, 'the fingerprint changed')
  const failure = await p.textContent('.fail-card')
  ok(/Finn/.test(failure) && /Ben/.test(failure), 'the failure names Finn and Ben')
  ok(/At least 90 cm/.test(failure) && /eight/.test(failure), 'with the limit and the count')
  ok((await states())[0].startsWith('Fails'), 'Movement fails: both formations are still correct')

  heading('The debugger')
  await p.click('text=Back a count'); await p.waitForTimeout(100); await p.click('text=The exact moment'); await p.waitForTimeout(100)
  await p.click('text=Find the smallest fix'); await p.waitForSelector('.tool-row', { timeout: T })
  await p.waitForFunction(() => document.querySelectorAll('.tool-row').length > 0 && !document.querySelector('.tool-row .pill.wait'), null, { timeout: T })
  const proved = await p.locator('.tool-row:has(.pill.ok)').count(), total = await p.locator('.tool-row').count()
  ok(proved > 0, `Lean judged ${total} candidate fixes and proved ${proved}`)

  heading('Act 5: fix it, using a fix Lean proved')
  await p.locator('.tool-row:has(.pill.ok) >> text=Use this').first().click(); await p.waitForTimeout(400); await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved.', 'the corrected routine is proved')
  ok((await p.textContent('.time')).endsWith('0:15'), 'and it keeps its timing')
  const fixedFp = await fp(); ok(fixedFp !== brokenFp && fixedFp !== originalFp, 'with its own fingerprint')

  heading('The time machine')
  await paneOf(p, 'History'); const hist = await p.locator('.hist > li').count(); ok(hist >= 3, `${hist} versions are in the history`)
  const checks = p.locator('.hist input[type=checkbox]'); await checks.first().check(); await checks.nth(1).check(); await p.waitForTimeout(200)
  ok(await p.locator('.ctable tr.changed').count() > 0, 'comparing versions shows which guarantees changed')
  await checks.first().uncheck(); await checks.nth(1).uncheck()

  heading('Going back')
  await p.locator('.hist > li').last().locator('button').click(); await p.waitForTimeout(500)
  ok(await p.textContent('.verdict h2') === 'Proved.' && await fp() === originalFp, 'an old version brings back its own proof')

  heading('Selecting a dancer')
  await p.locator('.proj button.row:has-text("Hugo")').click(); await p.waitForSelector('.inspector')
  ok((await p.textContent('.inspector h3')).includes('Hugo') && (await p.locator('.in-pairs li').count()) > 0, 'selecting a dancer shows their spacing against everyone')
  await p.click('.inspector >> text=Close')

  heading('Building a routine from a blank stage')
  await p.click('.brand'); await p.click('text=Place every dancer myself'); await p.waitForSelector('.plan', { timeout: T }); await p.waitForTimeout(400); await verdict(p); 
  ok(await p.textContent('.verdict h2') === 'Proved.', 'a blank stage with everyone in the wings is proved')
  ok((await p.textContent('.proj-title')).includes('0 on stage, 8 off stage'), 'all 8 dancers are accounted for, off stage')
  const pb = await p.locator('.plan > svg').boundingBox(), ps = Math.min(pb.width / 21600, pb.height / 9900), px = x => pb.x + pb.width / 2 + x * ps, py = y => pb.y + (pb.height - 9900 * ps) / 2 + 1200 * ps + (8000 - y) * ps
  const firstPlaces = await p.evaluate(() => [...document.querySelectorAll('.dancer-row .sec-sub')].map(e => e.textContent))
  ok(firstPlaces.every(x => x.includes('wing')), 'each dancer shows where they stand: ' + firstPlaces[0])
  if (process.env.SHOT) await p.screenshot({ path: process.env.SHOT })
  const place = async (x0, y0, x1, y1) => { await p.mouse.move(px(x0), py(y0)); await p.mouse.down(); await p.mouse.move(px(x1), py(y1), { steps: 5 }); await p.mouse.up(); await p.waitForTimeout(500) }
  await place(6900, 7000, -1200, 5500); await p.waitForSelector('.verify-card')
  ok((await p.textContent('.proj-title')).includes('1 on stage, 7 off stage'), 'dragging a dancer on stage updates the count')
  await p.click('.ftab-add'); await p.waitForTimeout(700)
  ok(await p.locator('.ftab').count() === 2 && await p.locator('.ftab.on[data-f="2"]').count() === 1, 'the plus button adds a formation and opens it')
  ok((await p.textContent('.proj-title')).includes('1 on stage'), 'it starts where the last formation ended')
  await place(-1200, 5500, 1200, 2500)
  await p.click('[data-f="1"]'); await p.waitForTimeout(250)
  ok((await p.locator('.dancer-row .sec-sub').first().textContent()).toLowerCase().includes('row'), 'each tab keeps its own positions')
  await p.click('text=Verify choreography'); await p.waitForTimeout(400); await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved.', 'Lean proves the routine you built')
  await p.click('.add-dancer'); await p.waitForTimeout(800); await p.waitForSelector('.verify-card'); ok(await p.locator('.dancer-row').count() === 9, 'adding a dancer puts them in the wings, and needs a new check')
  await p.click('[data-f="2"]'); await p.waitForTimeout(150); await p.click('.fremove'); await p.waitForTimeout(700); ok(await p.locator('.ftab').count() === 1, 'a formation can be removed')
  await p.click('text=Verify choreography'); await p.waitForTimeout(400); await verdict(p); ok(await p.textContent('.verdict h2') === 'Proved.', 'and the result is still proved')

  heading('Technical failure is not a verdict')
  await p.route('**/api/compose', r => r.fulfill({ status: 200, contentType: 'application/x-ndjson', body: '' }))
  await p.click('.top >> text=Change it'); await p.click('.dh-go'); await p.waitForFunction(() => /No verdict/.test(document.querySelector('.verdict')?.textContent ?? ''), null, { timeout: T })
  ok(!(await p.textContent('.verdict')).includes('unsafe'), 'a lost connection reads "no verdict", not "unsafe"')
  await p.unroute('**/api/compose')

  heading('Talking through a routine')
  await p.click('.brand'); await p.waitForSelector('.director-home')
  const say = async t => { await p.fill('.dr-input textarea', t); await p.keyboard.press('Enter'); await p.waitForTimeout(80) }
  await say('A fancy bhangra piece for eight dancers, 90 seconds')
  ok(/Got it/.test(await p.locator('.dr-msg.them').last().textContent()) && (await p.locator('.params select').first().inputValue()) === '8', 'the director reads it, and the settings show it')
  await say('half wait off stage'); await say('add a burst and a dhamaal')
  ok((await p.textContent('.dh-sum')).includes('Burst') && (await p.textContent('.dh-sum')).includes('Dhamaal') && (await p.textContent('.dh-sum')).includes('4 waiting'), 'the brief builds up')
  await p.click('.dr-tools >> text=Ideas'); await p.waitForSelector('.dr-ideas'); ok(await p.locator('.idea').count() >= 12, 'ideas from real forms and the Library'); await p.click('.dr-tools >> text=Ideas')
  await p.locator('.dr-tools input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Loved the spiral into a kolattam section') })
  await p.waitForTimeout(150); ok(/spiral/i.test(await p.locator('.dr-msg.them').last().textContent()), 'notes can be brought in as inspiration')
  await p.locator('.dr-tools input[type=file]').setInputFiles({ name: 'clip.mp4', mimeType: 'video/mp4', buffer: Buffer.from('x') })
  await p.waitForTimeout(150); ok(/can't watch video/.test(await p.locator('.dr-msg.them').last().textContent()), 'it says plainly it cannot read video')
  await p.click('.dh-go'); await p.waitForSelector('.rail .params', { timeout: T }); await p.waitForTimeout(300); await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved.', 'the routine is proved')
  ok((await p.locator('.rail .param').count()) >= 7, 'every setting stays in view')

  heading('Off-stage and on-stage dancers crossing')
  await paneOf(p, 'Crossings'); ok(await p.locator('.cross:has-text("Cast change")').count() >= 1, 'the rail lists the cast change')
  ok(/Lean proved they never get closer/.test(await p.locator('.cross').first().textContent()), 'and says what Lean proved about it')
  await p.locator('.cross:has-text("Cast change") >> text=Watch it').first().click(); await p.waitForTimeout(600); ok(await p.evaluate(() => !!document.querySelector('.stagebox canvas, .stagebox svg')), 'it can be watched')
  const crashBtn = p.locator('text=See the crash Lean rejected').first()
  ok(await crashBtn.count() === 1, 'the crossing Lean turned down can be shown')
  await crashBtn.click(); await p.waitForSelector('.crash-banner'); await p.waitForTimeout(400)
  ok(/This is not your routine/.test(await p.textContent('.crash-banner')) && await p.textContent('.verdict h2') === 'Proved.', 'it is labelled as rejected, and the real verdict is unchanged')
  for (const view of ['3D', 'Top view']) { await p.click(`.tab:has-text("${view}")`); await p.waitForTimeout(500); ok(await p.locator('.crash-banner').count() === 1, `the crash shows in ${view}`) }
  await p.click('text=Back to the safe version'); await p.waitForTimeout(200); ok(await p.locator('.crash-banner').count() === 0, 'and back to the safe version')

  heading('All four properties are on screen')
  for (const [key, name] of [['gap', 'No collisions'], ['bounds', 'Stays in bounds'], ['speed', 'Under the speed limit'], ['joins', 'No jumps between moves']]) ok(/Proved/.test(await p.textContent(`[data-gauge=${key}]`)) && (await p.textContent(`[data-gauge=${key}]`)).includes(name), `${name} is shown as proved`)
  await p.click('.tab:has-text("3D")'); await p.waitForTimeout(300); ok(await p.locator('.gauge').count() === 5, 'and Forgiving, in the 3D view too')
  ok(/Proved/.test(await p.textContent('[data-gauge=forgive]')), 'the forgiving theorem is proved'); await p.click('[data-gauge=speed] .g-deep'); await p.waitForTimeout(250); ok(!(await p.textContent('.time')).startsWith('0:00'), 'clicking a figure jumps to that moment')
  await p.click('.tab:has-text("Top view")')

  heading('A routine from a prompt can be edited')
  await p.click('.tab:has-text("Formations")'); await p.waitForSelector('.plan'); const tabsBefore = await p.locator('.ftab').count()
  ok(tabsBefore > 3 && await p.locator('.ftab-add').count() === 1, `it has ${tabsBefore} formation tabs and the add button`)
  ok(await p.locator('.plan').count() === 1 && /off stage/.test(await (async () => p.textContent('.proj-title'))()), 'and shows who is off stage')
  await p.locator('[data-f="3"]').click(); await p.waitForTimeout(200); ok(await p.locator('.fway select').count() === 1, 'each formation says how they travel there')
  await p.click('.ftab-add'); await p.waitForSelector('.verify-card', { timeout: T }); await p.waitForTimeout(400)
  ok(await p.locator('.ftab').count() === tabsBefore + 1, 'the plus button works on a routine from a prompt')
  await p.click('text=Verify choreography'); await p.waitForTimeout(400); await verdict(p); ok(await p.textContent('.verdict h2') === 'Proved.', 'and it is proved after the edit')

  heading('Shaping a path by hand')
  await p.locator('[data-f="2"]').click(); await p.waitForTimeout(300)
  const handle = p.locator('.bend-handle').first(); ok(await p.locator('.bend-handle').count() > 0, 'each moving dancer has a handle on their path')
  const hb = await handle.boundingBox(); await p.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2); await p.mouse.down(); await p.mouse.move(hb.x + hb.width / 2, hb.y - 26, { steps: 4 }); await p.mouse.up()
  await p.waitForSelector('.verify-card', { timeout: T }); await p.waitForTimeout(300); ok(/not checked/.test(await p.textContent('.verify-card')), 'a new path is not trusted until it is checked')
  await p.click('text=Verify choreography'); await p.waitForTimeout(400); await verdict(p)
  ok(/Proved\.|Proved unsafe\./.test(await p.textContent('.verdict h2')), `Lean judges the curved path: ${await p.textContent('.verdict h2')}`)

  heading('Changing it with words')
  await p.click('.top >> text=Change it'); await p.waitForSelector('.director-home'); ok(/What should change/.test(await p.textContent('.dr-next')), 'Change it goes back to the prompt page')
  ok(await p.locator('.stagebox').count() === 0, 'with no stage crowding it')
  await p.fill('.dr-input textarea', 'add a spiral'); await p.keyboard.press('Enter'); await p.waitForTimeout(100); await p.click('.dh-go'); await p.waitForSelector('.rail .params'); await p.waitForTimeout(400); await verdict(p)
  ok(await p.textContent('.verdict h2') === 'Proved.', 'and the changed routine is proved again')
  await paneOf(p, 'History'); ok(await p.locator('.hist > li').count() >= 2, 'with the earlier versions kept'); await paneOf(p, 'Crossings')

  heading('My routines')
  await p.click('.nav-links a:has-text("My routines")'); await p.waitForSelector('.file-card', { timeout: T })
  const saved = await p.locator('.file-card').count(); ok(saved >= 2, `${saved} routines were kept`)
  ok(await p.locator('.file-card .pill:has-text("Proved")').count() >= 1, 'with their results')
  await p.locator('.file-card >> text=Duplicate').first().click(); await p.waitForTimeout(100); ok(await p.locator('.file-card').count() === saved + 1, 'one can be duplicated')
  await p.locator('.file-card >> text=Delete').first().click(); await p.locator('.file-card >> text=Really delete').first().click(); await p.waitForTimeout(100); ok(await p.locator('.file-card').count() === saved, 'and deleted, after asking')
  await p.locator('.file-card >> text=Open').first().click(); await p.waitForSelector('.rail .params', { timeout: T }); await p.waitForTimeout(400); await verdict(p)
  ok(true, 'and reopened, and Lean checks it again')

  heading('Everything else')
  for (const [route, sel] of [['explore', '.poster'], ['files', '.file-card'], ['home', '.hero-home']]) { await p.goto(`${URL}/#/${route}`); await p.waitForSelector(sel, { timeout: 30000 }); ok(true, `${route} works`) }
  await p.goto(`${URL}/#/explore`); await p.fill('.search', 'kuthu'); await p.waitForTimeout(150); ok(await p.locator('.poster').count() >= 1, 'kuthu is in the library')
  await p.fill('.search', 'kolattam'); await p.waitForTimeout(150); ok(await p.locator('.poster').count() >= 1, 'South Indian styles are in the library')

  heading('On a phone')
  const m = await c.newPage(); await m.setViewportSize({ width: 390, height: 844 }); m.on('pageerror', e => errs.push(e.message))
  for (const route of ['home', 'explore', 'files', 'create']) {
    await m.goto(`${URL}/#/${route}`); await m.waitForTimeout(400)
    const over = await m.evaluate(() => Math.max(document.documentElement.scrollWidth - innerWidth, ...[...document.querySelectorAll('.page')].map(e => e.scrollWidth - e.clientWidth)))
    ok(over <= 0, `${route} has no sideways scroll`)
  }
  await m.close()
  ok(errs.length === 0, `no errors in the browser${errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''}`)
  console.log(`\n${passed} checks passed.`)
  await b.close()
})().catch(async e => { console.error(e.message.slice(0, 900)); process.exit(1) })
